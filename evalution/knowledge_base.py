def _extract_keywords(text):
    """提取文本中的有效关键词（2-4字的中文词组）"""
    keywords = []
    # 提取2字词组
    for i in range(len(text) - 1):
        word = text[i:i+2]
        if word not in STOP_WORDS and len(word.strip()) == 2:
            # 过滤纯标点和数字+单位
            if not all(c in '，。！？、；：""''（）【】《》…— \t\n' for c in word):
                keywords.append(word)
    # 提取3字词组（更有区分度）
    for i in range(len(text) - 2):
        word = text[i:i+3]
        if word not in STOP_WORDS and len(word.strip()) == 3:
            if not all(c in '，。！？、；：""''（）【】《》…— \t\n' for c in word):
                keywords.append(word)
    return keywords


def _calculate_relevance(query_keywords, chunk):
    """
    计算查询关键词与知识片段的相关性得分
    改进策略：
    1. 3字词权重3，2字词权重1（3字词更有区分度）
    2. 去掉连续匹配加分（之前导致不相关片段排名靠前）
    3. 对核心实体词（景区名、建筑名）给予额外权重
    """
    score = 0
    
    for kw in query_keywords:
        if kw in chunk:
            # 3字词权重更高（3分），2字词权重1分
            weight = 3 if len(kw) == 3 else 1
            score += weight
    
    return score


def retrieve_knowledge(scene, query, top_k=3):
    """
    优化的RAG检索函数
    改进点：
    1. 2字+3字关键词双重提取，提高匹配精度
    2. 加权评分：3字词权重更高
    3. 连续匹配加分：相近的关键词匹配给予额外得分
    4. 动态阈值：如果最高分太低，返回空列表（避免召回不相关内容）
    """
    if scene not in KNOWLEDGE_BASE:
        return []
    
    knowledge_chunks = KNOWLEDGE_BASE[scene]
    query_keywords = _extract_keywords(query)
    
    if not query_keywords:
        return knowledge_chunks[:top_k]  # 无法提取关键词时返回前几条
    
    # 计算每个知识片段的相关性得分
    scored_chunks = []
    for chunk in knowledge_chunks:
        score = _calculate_relevance(query_keywords, chunk)
        scored_chunks.append((chunk, score))
    
    # 按得分排序
    scored_chunks.sort(key=lambda x: x[1], reverse=True)
    
    # 动态阈值：最高分至少为1才返回结果
    if scored_chunks[0][1] == 0:
        return []
    
    # 返回top_k个有得分的结果
    result = [chunk for chunk, score in scored_chunks[:top_k] if score > 0]
    return result if result else []

